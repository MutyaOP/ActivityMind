def shade(cell, color):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color)
    tcpr.append(shd)


def table(caption, header, rows, widths=None, size=11):
    tab_no[0] += 1
    cp = p(f'{tab_no[0]}-кесте – {caption}', indent=False, after=3)
    cp.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=1, cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ''
        r = c.paragraphs[0].add_run(h)
        r.bold = True
        r.font.size = Pt(size)
        c.paragraphs[0].paragraph_format.first_line_indent = Cm(0)
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        shade(c, 'E7E6F7')
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            para = cells[i].paragraphs[0]
            para.paragraph_format.first_line_indent = Cm(0)
            para.alignment = WD_ALIGN_PARAGRAPH.LEFT
            r = para.add_run(str(v))
            r.font.size = Pt(size)
    # кесте тақырыбын әр бетте қайталау
    trpr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement('w:tblHeader')
    th.set(qn('w:val'), 'true')
    trpr.append(th)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


def figure(path, caption, explanation, width_cm=16.0, max_h_cm=21.0, crop=None):
    fig_no[0] += 1
    if crop:
        im = Image.open(path)
        cw, ch = im.size
        if ch > cw * crop:
            tmp = Path(tempfile.gettempdir()) / ('am_crop_' + Path(path).name)
            im.crop((0, 0, cw, int(cw * crop))).save(tmp)
            path = tmp
    w, h = Image.open(path).size
    width = width_cm
    if h / w * width > max_h_cm:
        width = max_h_cm * w / h
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.first_line_indent = Cm(0)
    para.paragraph_format.keep_with_next = True
    para.add_run().add_picture(str(path), width=Cm(width))
    cp = p(f'{fig_no[0]}-сурет – {caption}', align=WD_ALIGN_PARAGRAPH.CENTER, indent=False, after=6)
    cp.paragraph_format.keep_with_next = True
    for e in explanation:
        p(e)
    doc.add_paragraph()


def add_field(paragraph, instr):
    r = paragraph.add_run()
    f1 = OxmlElement('w:fldChar'); f1.set(qn('w:fldCharType'), 'begin')
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = instr
    f2 = OxmlElement('w:fldChar'); f2.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t'); t.text = 'Мазмұнды жаңарту үшін F9 басыңыз'
    f3 = OxmlElement('w:fldChar'); f3.set(qn('w:fldCharType'), 'end')
    for el in (f1, it, f2, t, f3):
        r._r.append(el)


def code(text, size=10):
    for line in text.strip('\n').split('\n'):
        para = doc.add_paragraph()
        para.paragraph_format.first_line_indent = Cm(0)
        para.alignment = WD_ALIGN_PARAGRAPH.LEFT
        r = para.add_run(line if line else ' ')
        r.font.name = 'Consolas'
        r._r.get_or_add_rPr().get_or_add_rFonts().set(qn('w:ascii'), 'Consolas')
        r.font.size = Pt(size)



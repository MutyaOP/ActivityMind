def p(text='', bold=False, italic=False, align=None, indent=True, size=None, after=0):
    para = doc.add_paragraph()
    if not indent:
        para.paragraph_format.first_line_indent = Cm(0)
    if align:
        para.alignment = align
    para.paragraph_format.space_after = Pt(after)
    # **қалың** белгісін қолдау
    parts = text.split('**')
    for i, part in enumerate(parts):
        if not part:
            continue
        r = para.add_run(part)
        r.bold = bold or (i % 2 == 1)
        r.italic = italic
        if size:
            r.font.size = Pt(size)
    return para


def bullets(items, numbered=False):
    for i, it in enumerate(items, 1):
        para = p(('%d) ' % i if numbered else '– ') + it)
        para.paragraph_format.first_line_indent = Cm(0)
        para.paragraph_format.left_indent = Cm(1.25)


def h1(text, new_page=True):
    if new_page:
        doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
        doc.paragraphs[-1].paragraph_format.first_line_indent = Cm(0)
    return doc.add_heading(text, level=1)


